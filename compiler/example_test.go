package compiler

import (
	"bytes"
	"flag"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"gopkg.in/yaml.v3"
)

var update = flag.Bool("update", false, "rewrite example/compiled/ from the current compiler")

const example = "../example"

// exampleInputs: the platform values, then the given values files.
func exampleInputs(t *testing.T, files ...string) Inputs {
	t.Helper()
	in := Inputs{
		Chart:     os.DirFS(filepath.Join(example, "webapp")),
		Contracts: os.DirFS(filepath.Join(example, "contracts")),
		Release:   "demo-webapp",
		Namespace: "demo",
	}
	for _, f := range append([]string{filepath.Join(example, "platform-values.yaml")}, files...) {
		b, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		v, err := ParseValues(b)
		if err != nil {
			t.Fatalf("%s: %v", f, err)
		}
		in.Values = append(in.Values, v)
	}
	return in
}

// TestExample compiles every example/values/<case>.yaml and compares the
// final values, objects and dependencies with example/compiled/<case>.yaml.
func TestExample(t *testing.T) {
	def, err := LoadDefinition(os.DirFS(example))
	if err != nil {
		t.Fatal(err)
	}
	cases, _ := filepath.Glob(filepath.Join(example, "values", "*.yaml"))
	if len(cases) == 0 {
		t.Fatal("no example values")
	}
	for _, f := range cases {
		name := strings.TrimSuffix(filepath.Base(f), ".yaml")
		t.Run(name, func(t *testing.T) {
			res, err := Compile(def, exampleInputs(t, f))
			if err != nil {
				t.Fatal(err)
			}
			var buf bytes.Buffer
			buf.WriteString("# Generated by `go test ./compiler -update`. Do not edit.\n")
			enc := yaml.NewEncoder(&buf)
			enc.SetIndent(2)
			if err := enc.Encode(map[string]any{"values": res.Values, "objects": res.Objects, "dependencies": res.Dependencies}); err != nil {
				t.Fatal(err)
			}
			golden := filepath.Join(example, "compiled", name+".yaml")
			if *update {
				if err := os.WriteFile(golden, buf.Bytes(), 0o644); err != nil {
					t.Fatal(err)
				}
				return
			}
			want, err := os.ReadFile(golden)
			if err != nil {
				t.Fatalf("%v (run go test ./compiler -update)", err)
			}
			if !bytes.Equal(buf.Bytes(), want) {
				t.Errorf("%s differs from the compile, run go test ./compiler -update and review the diff", golden)
			}
		})
	}
}

// TestExampleErrors: every testdata/<case>.yaml, applied over the platform
// values, must fail with the message of its first line (# error: ...).
func TestExampleErrors(t *testing.T) {
	def, err := LoadDefinition(os.DirFS(example))
	if err != nil {
		t.Fatal(err)
	}
	cases, _ := filepath.Glob(filepath.Join("..", "testdata", "*.yaml"))
	if len(cases) == 0 {
		t.Fatal("no testdata")
	}
	for _, f := range cases {
		t.Run(strings.TrimSuffix(filepath.Base(f), ".yaml"), func(t *testing.T) {
			b, err := os.ReadFile(f)
			if err != nil {
				t.Fatal(err)
			}
			first, _, _ := strings.Cut(string(b), "\n")
			want, ok := strings.CutPrefix(first, "# error: ")
			if !ok {
				t.Fatalf("first line must be \"# error: <message>\", got %q", first)
			}
			_, err = Compile(def, exampleInputs(t, f))
			if err == nil || !strings.Contains(err.Error(), want) {
				t.Errorf("got %v, want an error containing %q", err, want)
			}
		})
	}
}
