package compiler

import (
	"bytes"
	"fmt"
	"maps"

	"go.yaml.in/yaml/v3"
)

// The files of a compile (Write). The package's chart is not among them.
const (
	// ValuesFile holds the values of the catalog's chart, given with -f:
	// as user values, their nulls delete the upstream defaults.
	ValuesFile = "values.yaml"
	// ObjectsValuesFile holds the values of the okdp-objects chart, the
	// release <release>-okdp. It is installed before the catalog's chart,
	// because it creates the Secrets that chart uses.
	ObjectsValuesFile = "okdp-objects.values.yaml"
	// InfoFile holds what the instance publishes.
	InfoFile = "okdp.info.yaml"
	// Generated is the first line of the files that are not to be edited.
	Generated = "# Code generated by okdp-compile. DO NOT EDIT.\n"
)

// Write returns the files of a compile, by name: ValuesFile,
// ObjectsValuesFile when res has objects, and InfoFile when the instance
// publishes something. A dependency that the mapping leaves out is
// switched off: it must declare condition: <key>.enabled, else Write
// fails. res must come from a compile with a Finalize.
func Write(res *Result) (map[string][]byte, error) {
	values := ChartValues(res)
	for _, d := range res.Chart.Dependencies {
		if _, ok := values[d.Key()]; ok {
			continue
		}
		if d.Condition == nil {
			return nil, fmt.Errorf("%s: the mapping leaves it out: installed as it is, the chart needs condition: %s.enabled in its Chart.yaml", d.Key(), d.Key())
		}
		values[d.Key()] = map[string]any{"enabled": false}
	}
	objects, err := ObjectsChartValues(res)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	generated := map[string]any{}
	if len(values) > 0 {
		generated[ValuesFile] = values
	}
	if objects != nil {
		generated[ObjectsValuesFile] = objects
	}
	for name, v := range generated {
		b, err := encode(v)
		if err != nil {
			return nil, err
		}
		files[name] = append([]byte(Generated), b...)
	}
	if i := res.Info; i.URL != "" || i.Usage != "" || len(i.Provides) > 0 {
		if files[InfoFile], err = encode(i); err != nil {
			return nil, err
		}
	}
	return files, nil
}

// ChartValues returns the values of the package's charts, in a new map.
func ChartValues(res *Result) map[string]map[string]any {
	return maps.Collect(maps.All(res.Values))
}

// ObjectsChartValues returns the values of the okdp-objects chart of res,
// or nil when res has no object. The objects are one YAML stream in a
// string, so that Helm changes nothing in them, a {{ or a null included.
func ObjectsChartValues(res *Result) (map[string]any, error) {
	if len(res.Objects) == 0 {
		return nil, nil
	}
	var stream bytes.Buffer
	enc := yaml.NewEncoder(&stream)
	enc.SetIndent(2)
	for _, o := range res.Objects {
		if err := enc.Encode(o); err != nil {
			return nil, err
		}
	}
	return map[string]any{ObjectsValue: stream.String()}, nil
}

func encode(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}
