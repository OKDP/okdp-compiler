package compiler

import (
	"bytes"
	"fmt"
	"maps"
	"strings"

	"go.yaml.in/yaml/v3"

	"github.com/okdp/okdp-compiler/value"
)

// The files of a compile (Write). No chart among them: the catalog's package
// is installed as it is.
const (
	// ValuesFile: the values of the catalog's chart, helm install <release>
	// <package> -f values.yaml. Outside any chart, it is read as user values,
	// its nulls deleting the upstream defaults.
	ValuesFile = "values.yaml"
	// ObjectsValuesFile: the values of the okdp-objects chart, helm install
	// <release>-okdp okdp-objects -f okdp-objects.values.yaml, before the
	// catalog's chart, whose Secrets it creates.
	ObjectsValuesFile = "okdp-objects.values.yaml"
	// InfoFile: what the instance publishes.
	InfoFile = "okdp.info.yaml"
	// Generated: the first line of the files that are not to be edited.
	Generated = "# Code generated by okdp-compile. DO NOT EDIT.\n"
)

// Write: the files of a compile, name -> content: ValuesFile, the final
// values of each key of the package, a dependency the mapping leaves out
// switched off (it must declare condition: <key>.enabled); ObjectsValuesFile,
// when res has objects or OAuth clients; InfoFile, when the instance publishes
// something. res comes from a compile with a Finalize.
func Write(res *Result) (map[string][]byte, error) {
	values := ChartValues(res)
	for _, d := range res.Chart.Dependencies {
		if _, ok := values[d.Key()]; ok {
			continue
		}
		if d.Condition == nil {
			return nil, fmt.Errorf("%s: the mapping leaves it out: installed as it is, the chart needs condition: %s.enabled in its Chart.yaml", d.Key(), d.Key())
		}
		values[d.Key()] = map[string]any{"enabled": false}
	}
	objects, err := ObjectsChartValues(res)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	generated := map[string]any{}
	if len(values) > 0 {
		generated[ValuesFile] = values
	}
	if objects != nil {
		generated[ObjectsValuesFile] = objects
	}
	for name, v := range generated {
		b, err := encode(v)
		if err != nil {
			return nil, err
		}
		files[name] = append([]byte(Generated), b...)
	}
	if i := res.Info; i.URL != "" || i.Usage != "" || len(i.Provides) > 0 {
		if files[InfoFile], err = encode(i); err != nil {
			return nil, err
		}
	}
	return files, nil
}

// ChartValues: the values of the charts of the package, those of res the
// compiler did not add itself, in a new map.
func ChartValues(res *Result) map[string]map[string]any {
	values := maps.Collect(maps.All(res.Values))
	for _, k := range res.OwnCharts {
		delete(values, k)
	}
	return values
}

// ObjectsChartValues: the values of the okdp-objects chart of res: its
// objects as one YAML stream, a string, so that Helm changes neither the {{
// of an ExternalSecret's template, nor a null, nor an integer beyond the
// precision of a float64; and the values of each OAuth client, client<i>, in
// the order of their keys. nil without either.
func ObjectsChartValues(res *Result) (map[string]any, error) {
	out := map[string]any{}
	if len(res.Objects) > 0 {
		// Copies: what Argo CD is told of the objects Helm keeps changes
		// them, the Result stays as Compile returned it.
		kept := make([]map[string]any, len(res.Objects))
		for i, o := range res.Objects {
			kept[i] = value.AsMap(value.Copy(o))
		}
		keepSynced(res.KeepSync, kept)
		var stream bytes.Buffer
		enc := yaml.NewEncoder(&stream)
		enc.SetIndent(2)
		for _, o := range kept {
			if err := enc.Encode(o); err != nil {
				return nil, err
			}
		}
		out[ObjectsValue] = stream.String()
	}
	for i, key := range res.OwnCharts {
		client := maps.Clone(res.Values[key])
		client["enabled"] = true
		out[fmt.Sprintf("client%d", i)] = client
	}
	if len(out) == 0 {
		return nil, nil
	}
	return out, nil
}

// encode: v as YAML, indented by 2 spaces.
func encode(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// keepSynced: objects, each one Helm keeps with Argo CD's sync options of k
// added to those of its sync-options annotation, comma-separated, unless it
// sets an option of that name already (Prune=confirm stays); an item of a
// List alike. The other objects are left as they are.
func keepSynced(k KeepSync, objects []map[string]any) {
	if k.Annotation == "" {
		return
	}
	for _, o := range objects {
		meta, _ := o["metadata"].(map[string]any)
		if annotations, ok := meta["annotations"].(map[string]any); ok && k.Kept(annotations) {
			var options []string
			if s, ok := annotations[k.SyncOptions].(string); ok && strings.TrimSpace(s) != "" {
				options = strings.Split(s, ",")
			}
			set := map[string]bool{}
			for _, opt := range options {
				name, _, _ := strings.Cut(strings.TrimSpace(opt), "=")
				set[name] = true
			}
			for _, opt := range k.Options {
				if name, _, _ := strings.Cut(opt, "="); !set[name] {
					options = append(options, opt)
				}
			}
			annotations = maps.Clone(annotations)
			annotations[k.SyncOptions] = strings.Join(options, ",")
			meta = maps.Clone(meta)
			meta["annotations"] = annotations
			o["metadata"] = meta
		}
		var items []map[string]any
		for _, i := range value.AsList(o["items"]) {
			if m, ok := i.(map[string]any); ok {
				items = append(items, m)
			}
		}
		keepSynced(k, items)
	}
}
