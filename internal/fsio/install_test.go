// TestInstall: the script that installs each chart with the upstream chart
// rendering it, the OAuth clients first (Result.ClientCharts; a key that
// only ends like one, here a chart of service.yaml, with the others), a
// word the shell reads specially quoted; what it cannot install is refused.
func TestInstall(t *testing.T) {
	res := &okdp.Result{
		Values: map[string]map[string]any{"oidc-dcr": {}, "admin-oidc-dcr": {}, "app": {}},
		Charts: map[string]chart.Ref{
			"oidc-dcr":       okdp.DcrSource,
			"admin-oidc-dcr": okdp.DcrSource,
			"app":            {Repository: "https://charts.example.org/a?b&c", Chart: "app", Version: "1.0.0"},
		},
		ClientCharts: []string{"oidc-dcr"},
		Release:      "demo",
		Namespace:    "ns",
	}
	want := `#!/bin/sh
# Code generated by okdp-compile. DO NOT EDIT.
# Installs demo in the namespace ns, one Helm release per chart: its
# upstream chart with its values file. Recompile the instance to change it.
set -eu
cd "$(dirname "$0")"
helm upgrade --install demo-oidc-dcr oci://quay.io/adaltas/oidc-dcr --version 0.5.0 --namespace ns -f oidc-dcr.values.yaml
helm upgrade --install demo-admin-oidc-dcr oci://quay.io/adaltas/oidc-dcr --version 0.5.0 --namespace ns -f admin-oidc-dcr.values.yaml
helm upgrade --install demo-app app --repo 'https://charts.example.org/a?b&c' --version 1.0.0 --namespace ns -f app.values.yaml
`
	if files, err := Write(res, Output{Install: true}); err != nil || string(files[InstallScript]) != want {
		t.Errorf("got %v %s, want %s", err, files[InstallScript], want)
	}
	for name, tc := range map[string]struct {
		res  okdp.Result
		want string
	}{
		"no release": {okdp.Result{Namespace: "ns"}, `Result.Release "", Result.Namespace "ns": the release and namespace of the compile`},
		// Two keys, one release once cut to 53 characters.
		"one release": {okdp.Result{
			Values:  map[string]map[string]any{"app-1": {}, "app-2": {}},
			Charts:  map[string]chart.Ref{"app-1": {}, "app-2": {}},
			Release: strings.Repeat("r", 49), Namespace: "ns",
		}, `charts "app-1" and "app-2": one Helm release, "` + strings.Repeat("r", 49) + `-app", once <release>-<key> is cut to 53 characters`},
	} {
		if _, err := Write(&tc.res, Output{Install: true}); err == nil || !strings.HasPrefix(err.Error(), tc.want) {
			t.Errorf("%s: got %v, want %s", name, err, tc.want)
		}
	}
}

// TestInstallUmbrella: the script that installs the umbrella chart as one
// release, its dependencies built in a copy; a release or namespace it
// cannot install under is refused.
func TestInstallUmbrella(t *testing.T) {
	want := `#!/bin/sh
# Code generated by okdp-compile. DO NOT EDIT.
# Installs demo in the namespace ns, one Helm release: the
# umbrella chart of this directory, its dependencies built in a copy, with
# its values. Recompile the instance to change it.
set -eu
cd "$(dirname "$0")"
chart=$(mktemp -d)
trap 'rm -rf "$chart"' EXIT
cp Chart.yaml "$chart"
helm dependency build "$chart"
helm upgrade --install demo "$chart" --namespace ns -f instance.values.yaml
`
	res := &okdp.Result{Release: "demo", Namespace: "ns", Service: "demo", Version: "1.0.0"}
	o := Output{Umbrella: true, Install: true}
	if files, err := Write(res, o); err != nil || string(files[InstallScript]) != want {
		t.Errorf("got %v %s, want %s", err, files[InstallScript], want)
	}
	res.Release = "Demo"
	if _, err := Write(res, o); err == nil || !strings.HasPrefix(err.Error(), `Result.Release "Demo", Result.Namespace "ns": the release and namespace of the compile`) {
		t.Errorf("a bad release: got %v", err)
	}
}
