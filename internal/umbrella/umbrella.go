// Package umbrella writes a compile as the files of okdp-compile (Write):
// one chart for the whole instance, an umbrella over the upstream charts of
// its keys, for one Helm release per instance under the release name its
// values were compiled for, and the instances it depends on. The caller
// writes them (the CLI to a directory, a server to git).
package umbrella

import (
	"bytes"
	"fmt"
	"maps"
	"slices"

	"go.yaml.in/yaml/v3"

	"github.com/okdp/okdp-compiler/internal/chart"
	"github.com/okdp/okdp-compiler/internal/okdp"
)

// The files Write gives besides Chart.yaml.
const (
	// ValuesFile: the umbrella's values file, given to Helm as user values
	// (helm -f, Argo CD valueFiles, Flux valuesFrom). As the chart's own
	// values.yaml they would be defaults, and Helm drops the nulls of
	// defaults: a null that deletes an upstream default would be lost.
	ValuesFile = "instance.values.yaml"
	// DependenciesFile: Result.Dependencies as a YAML list, [] when there is
	// none: the instances the connection references point to, for a
	// deployer that orders the releases (Flux dependsOn, Argo CD sync
	// waves). Helm ignores it.
	DependenciesFile = "okdp.dependencies.yaml"
)

// generated: the first line of the umbrella's values, Go's mark of a
// generated file, which GitHub, linters and editors know.
const generated = "# Code generated by okdp-compile. DO NOT EDIT.\n"

// chartYAML: the Chart.yaml of an umbrella, in Helm's key order.
type chartYAML struct {
	APIVersion   string       `yaml:"apiVersion"`
	Name         string       `yaml:"name"`
	Version      string       `yaml:"version"`
	Dependencies []dependency `yaml:"dependencies"`
}

// dependency: the upstream chart of a key.
type dependency struct {
	Name       string `yaml:"name"`
	Alias      string `yaml:"alias,omitempty"`
	Repository string `yaml:"repository"`
	Version    string `yaml:"version"`
}

// Write: what `okdp-compile -o <dir>` writes for res, file name -> content:
//
//   - Chart.yaml, the chart of the instance, named and versioned after
//     service.yaml (Result.Service, Result.Version), with one dependency
//     per compiled key: its upstream chart (Result.Charts), aliased to the
//     key when the key is not the chart's name (Helm then names the
//     subchart after the key: its .Chart.Name is the key);
//   - ValuesFile, the final values of each key under the key, each with its
//     own global, marked generated;
//   - DependenciesFile.
//
// The YAML files are indented by 2 spaces. Every file is built before
// Write returns: one that fails leaves the caller nothing to write. res is
// what Compile returned: Write does not check it again.
func Write(res *okdp.Result) (map[string][]byte, error) {
	if !chart.IsVersion(res.Version) {
		return nil, fmt.Errorf("service.yaml: version %q: the version of the umbrella chart, SemVer (1.2.3)", res.Version)
	}
	c := chartYAML{APIVersion: "v2", Name: res.Service, Version: res.Version}
	values := map[string]any{}
	for _, key := range slices.Sorted(maps.Keys(res.Values)) {
		ref := res.Charts[key]
		d := dependency{Name: ref.Chart, Repository: ref.Repository, Version: ref.Version}
		if key != ref.Chart {
			d.Alias = key
		}
		c.Dependencies = append(c.Dependencies, d)
		values[key] = res.Values[key]
	}
	files := map[string][]byte{}
	for name, v := range map[string]any{"Chart.yaml": c, ValuesFile: values, DependenciesFile: res.Dependencies} {
		var buf bytes.Buffer
		if name == ValuesFile {
			buf.WriteString(generated)
		}
		enc := yaml.NewEncoder(&buf)
		enc.SetIndent(2)
		if err := enc.Encode(v); err != nil {
			return nil, err
		}
		files[name] = buf.Bytes()
	}
	return files, nil
}
